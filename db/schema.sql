-- ---------- Tables ----------
create table if not exists availability (
  id bigint generated by default as identity primary key,
  event_date date not null,
  session    text not null check (session in ('daytime','evening')),
  note       text,
  updated_at timestamptz not null default now(),
  unique (event_date, session)              -- a row here = that session is RESERVED
);

create table if not exists bookings (
  id bigint generated by default as identity primary key,
  event_date date not null,
  session    text not null check (session in ('daytime','evening')),
  name       text not null,
  email      text not null,
  phone      text,
  event_type text,
  guests     integer,
  status     text not null default 'pending' check (status in ('pending','confirmed','declined')),
  created_at timestamptz not null default now()   -- when the enquiry was submitted
);
-- payment tracking (added for reserved bookings)
alter table bookings add column if not exists payment_status text not null default 'unpaid';
alter table bookings add column if not exists amount_paid    numeric(12,2);
alter table bookings add column if not exists receipt_number text;
alter table bookings add column if not exists payment_note   text;
do $$ begin
  if not exists (select 1 from pg_constraint where conname='bookings_payment_status_chk') then
    alter table bookings add constraint bookings_payment_status_chk
      check (payment_status in ('unpaid','part','full'));
  end if;
end $$;

-- staff with roles: 'admin' | 'finance' | 'estate'
create table if not exists admins (
  user_id text primary key,                 -- the staff member's auth id (JWT "sub")
  label   text
);
alter table admins add column if not exists role       text not null default 'admin';
alter table admins add column if not exists email      text;
alter table admins add column if not exists created_at timestamptz not null default now();
do $$ begin
  if not exists (select 1 from pg_constraint where conname='admins_role_chk') then
    alter table admins add constraint admins_role_chk check (role in ('admin','finance','estate'));
  end if;
end $$;

-- in-app notifications (one per new booking; visible to all staff)
create table if not exists notifications (
  id bigint generated by default as identity primary key,
  booking_id bigint references bookings(id) on delete cascade,
  message    text not null,
  read       boolean not null default false,
  created_at timestamptz not null default now()
);

-- ---------- Helper functions (SECURITY DEFINER so they can read admins past RLS) ----------
create or replace function public.my_role() returns text
  language sql stable security definer
  as $$ select role from public.admins where user_id = auth.user_id() limit 1; $$;
create or replace function public.is_staff() returns boolean
  language sql stable security definer
  as $$ select exists (select 1 from public.admins where user_id = auth.user_id()); $$;
create or replace function public.is_admin() returns boolean
  language sql stable security definer
  as $$ select exists (select 1 from public.admins where user_id = auth.user_id() and role = 'admin'); $$;

-- ---------- Notify on every new booking ----------
create or replace function public.notify_new_booking() returns trigger
  language plpgsql security definer as $$
begin
  insert into public.notifications (booking_id, message)
  values (NEW.id, NEW.name || ' — ' || to_char(NEW.event_date,'Dy DD Mon') || ' · ' || NEW.session);
  return NEW;
end; $$;
drop trigger if exists trg_notify_new_booking on bookings;
create trigger trg_notify_new_booking after insert on bookings
  for each row execute function public.notify_new_booking();

-- ---------- Grants (the "Grant public schema access" checkbox covers 'authenticated' on the base tables) ----------
grant usage on schema public to anonymous;
grant select on availability to anonymous;
grant insert on bookings    to anonymous;
grant usage, select on all sequences in schema public to anonymous;
grant execute on function public.my_role(), public.is_staff(), public.is_admin() to authenticated, anonymous;
grant select, update on notifications to authenticated;

-- ---------- Row-Level Security ----------
alter table availability  enable row level security;
alter table bookings      enable row level security;
alter table admins        enable row level security;
alter table notifications enable row level security;

-- availability: anyone reads; admin + estate write
drop policy if exists availability_public_read on availability;
drop policy if exists availability_admin_write on availability;
drop policy if exists availability_staff_write on availability;
create policy availability_public_read on availability
  for select to anonymous, authenticated using (true);
create policy availability_staff_write on availability
  for all to authenticated
  using (public.my_role() in ('admin','estate'))
  with check (public.my_role() in ('admin','estate'));

-- bookings: public inserts; all staff read & update
drop policy if exists bookings_public_insert on bookings;
drop policy if exists bookings_admin_read    on bookings;
drop policy if exists bookings_admin_update  on bookings;
drop policy if exists bookings_staff_read    on bookings;
drop policy if exists bookings_staff_update  on bookings;
create policy bookings_public_insert on bookings
  for insert to anonymous, authenticated with check (true);
create policy bookings_staff_read on bookings
  for select to authenticated using (public.is_staff());
create policy bookings_staff_update on bookings
  for update to authenticated using (public.is_staff()) with check (public.is_staff());

-- admins (staff): staff can view the list; only admins add / change / remove
drop policy if exists admins_select_staff on admins;
drop policy if exists admins_admin_write  on admins;
create policy admins_select_staff on admins
  for select to authenticated using (public.is_staff());
create policy admins_admin_write on admins
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- notifications: staff read + mark read
drop policy if exists notif_staff_read   on notifications;
drop policy if exists notif_staff_update on notifications;
create policy notif_staff_read on notifications
  for select to authenticated using (public.is_staff());
create policy notif_staff_update on notifications
  for update to authenticated using (public.is_staff()) with check (public.is_staff());
