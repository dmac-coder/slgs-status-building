-- audit log (written only by SECURITY DEFINER triggers -> cannot be forged by clients)
create table if not exists audit_log (
  id bigint generated by default as identity primary key,
  actor_user_id text,
  actor_label   text,
  action        text not null,
  detail        text,
  booking_id    bigint,
  created_at    timestamptz not null default now()
);

create or replace function public.audit(p_action text, p_detail text, p_booking bigint) returns void
  language plpgsql security definer as $$
declare lbl text;
begin
  select coalesce(label, role) into lbl from public.admins where user_id = auth.user_id();
  insert into public.audit_log(actor_user_id, actor_label, action, detail, booking_id)
  values (auth.user_id(), lbl, p_action, p_detail, p_booking);
end; $$;

create or replace function public.audit_availability() returns trigger
  language plpgsql security definer as $$
begin
  if TG_OP='INSERT' then perform public.audit('session_reserved','Reserved '||NEW.event_date||' · '||NEW.session, null);
  elsif TG_OP='DELETE' then perform public.audit('session_opened','Opened '||OLD.event_date||' · '||OLD.session, null);
  end if; return null;
end; $$;
drop trigger if exists trg_audit_availability on availability;
create trigger trg_audit_availability after insert or delete on availability for each row execute function public.audit_availability();

create or replace function public.audit_bookings() returns trigger
  language plpgsql security definer as $$
begin
  if NEW.status is distinct from OLD.status then perform public.audit('booking_status', NEW.name||' · '||NEW.status, NEW.id); end if;
  if NEW.amount_due is distinct from OLD.amount_due then perform public.audit('amount_due', NEW.name||' · due '||coalesce(NEW.amount_due::text,'—'), NEW.id); end if;
  if NEW.security_deposit is distinct from OLD.security_deposit then perform public.audit('deposit_set', NEW.name||' · deposit '||coalesce(NEW.security_deposit::text,'—'), NEW.id); end if;
  if NEW.refund_status is distinct from OLD.refund_status and NEW.refund_status='approved' then perform public.audit('refund_approved', NEW.name||' · deposit refund approved', NEW.id); end if;
  return null;
end; $$;
drop trigger if exists trg_audit_bookings on bookings;
create trigger trg_audit_bookings after update on bookings for each row execute function public.audit_bookings();

create or replace function public.audit_payments() returns trigger
  language plpgsql security definer as $$
declare nm text;
begin
  select name into nm from public.bookings where id = NEW.booking_id;
  perform public.audit('payment', coalesce(nm,'#'||NEW.booking_id)||' · '||to_char(NEW.amount,'FM999999990.00')||coalesce(' · '||NEW.receipt_number,''), NEW.booking_id);
  return null;
end; $$;
drop trigger if exists trg_audit_payments on payments;
create trigger trg_audit_payments after insert on payments for each row execute function public.audit_payments();

create or replace function public.audit_admins() returns trigger
  language plpgsql security definer as $$
begin
  if TG_OP='INSERT' then perform public.audit('staff_added', coalesce(NEW.label,NEW.user_id)||' · '||NEW.role, null);
  elsif TG_OP='DELETE' then perform public.audit('staff_removed', coalesce(OLD.label,OLD.user_id), null);
  elsif TG_OP='UPDATE' and NEW.role is distinct from OLD.role then perform public.audit('staff_role', coalesce(NEW.label,NEW.user_id)||' → '||NEW.role, null);
  end if; return null;
end; $$;
drop trigger if exists trg_audit_admins on admins;
create trigger trg_audit_admins after insert or update or delete on admins for each row execute function public.audit_admins();

