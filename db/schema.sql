-- availability: anyone reads; admin + estate write
drop policy if exists availability_public_read on availability;
drop policy if exists availability_admin_write on availability;
drop policy if exists availability_staff_write on availability;
create policy availability_public_read on availability
  for select to anonymous, authenticated using (true);
create policy availability_staff_write on availability
  for all to authenticated
  using (public.my_role() in ('admin','estate'))
  with check (public.my_role() in ('admin','estate'));

