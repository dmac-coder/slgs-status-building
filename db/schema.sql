-- =====================================================================
-- Payments ledger: amount due, part/balance payments, per-payment receipts
-- (re-run safe). Status & amount_paid are kept in sync by triggers.
-- =====================================================================
alter table bookings add column if not exists amount_due numeric(12,2);
alter table bookings alter column amount_paid set default 0;

create table if not exists payments (
  id bigint generated by default as identity primary key,
  booking_id bigint not null references bookings(id) on delete cascade,
  amount     numeric(12,2) not null check (amount > 0),
  receipt_number text,
  note       text,
  created_at timestamptz not null default now()
);

-- recompute a booking's paid total + status from its payments
create or replace function public.recalc_booking_payment(bid bigint) returns void
  language plpgsql security definer as $$
declare paid numeric(12,2); due numeric(12,2); st text;
begin
  select coalesce(sum(amount),0) into paid from public.payments where booking_id = bid;
  select amount_due into due from public.bookings where id = bid;
  if paid <= 0 then st := 'unpaid';
  elsif due is not null and due > 0 and paid >= due then st := 'full';
  else st := 'part';
  end if;
  update public.bookings set amount_paid = paid, payment_status = st where id = bid;
end; $$;

-- after any payment change: recompute the booking and (on new payment) notify staff
create or replace function public.payments_after_change() returns trigger
  language plpgsql security definer as $$
declare bid bigint; bk public.bookings; bal numeric(12,2);
begin
  bid := coalesce(NEW.booking_id, OLD.booking_id);
  perform public.recalc_booking_payment(bid);
  if TG_OP = 'INSERT' then
    select * into bk from public.bookings where id = bid;
    if bk.payment_status = 'full' then
      insert into public.notifications (booking_id, message)
        values (bid, 'Payment completed — ' || bk.name || ' · ' || to_char(bk.event_date,'Dy DD Mon'));
    else
      bal := coalesce(bk.amount_due,0) - coalesce(bk.amount_paid,0);
      insert into public.notifications (booking_id, message)
        values (bid, 'Part payment received — ' || bk.name ||
          case when bk.amount_due is not null then ' · balance ' || to_char(bal,'FM999999990.00') || ' outstanding' else ' · balance outstanding' end);
    end if;
  end if;
  return null;
end; $$;
drop trigger if exists trg_payments_change on payments;
create trigger trg_payments_change after insert or update or delete on payments
  for each row execute function public.payments_after_change();

-- recompute status when the agreed amount_due changes on a booking
create or replace function public.bookings_recalc_status() returns trigger
  language plpgsql security definer as $$
declare paid numeric(12,2);
begin
  if NEW.amount_due is distinct from OLD.amount_due then
    select coalesce(sum(amount),0) into paid from public.payments where booking_id = NEW.id;
    NEW.amount_paid := paid;
    if paid <= 0 then NEW.payment_status := 'unpaid';
    elsif NEW.amount_due is not null and NEW.amount_due > 0 and paid >= NEW.amount_due then NEW.payment_status := 'full';
    else NEW.payment_status := 'part';
    end if;
  end if;
  return NEW;
end; $$;
drop trigger if exists trg_bookings_recalc on bookings;
create trigger trg_bookings_recalc before update on bookings
  for each row execute function public.bookings_recalc_status();

grant select, insert, update, delete on payments to authenticated;
grant usage, select on all sequences in schema public to authenticated;
alter table payments enable row level security;
drop policy if exists payments_staff_read on payments;
drop policy if exists payments_pay_write  on payments;
create policy payments_staff_read on payments
  for select to authenticated using (public.is_staff());
create policy payments_pay_write on payments
  for all to authenticated
  using (public.my_role() in ('admin','finance'))
  with check (public.my_role() in ('admin','finance'));
